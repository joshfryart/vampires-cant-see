#!/usr/bin/env node
// Figure contact sheet builder.
//   node tools/build-figure-sheet.mjs [outPath] [--legacy-only]
// 1. Writes tools/figure-v016.js: the v0.16.0 js/figure.js (git show <LEGACY_REF>:js/figure.js), renamed to
//    VCS.FigureV016 so the sheet can draw the old figure next to the new one. Nothing under js/ is touched.
// 2. Inlines every <script src> of tools/figure-sheet.html (the real game modules, the legacy copy and the sheet
//    script) into ONE self-contained HTML file: no external requests, works offline and in a sandboxed iframe.
//    Default outPath: tests/out/figure-sheet-standalone.html (git-ignored).

import { execFileSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const LEGACY_REF = '9460bc0'; // v0.16.0
const LEGACY = join(ROOT, 'tools', 'figure-v016.js');
const SHEET = join(ROOT, 'tools', 'figure-sheet.html');

function legacySource() {
  try {
    return execFileSync('git', ['show', LEGACY_REF + ':js/figure.js'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
  } catch (e) {
    return null;
  }
}

function writeLegacy() {
  const src = legacySource();
  if (!src) {
    if (existsSync(LEGACY)) { process.stdout.write('git unavailable, keeping existing ' + LEGACY + '\n'); return; }
    throw new Error('cannot read ' + LEGACY_REF + ':js/figure.js and no tools/figure-v016.js exists');
  }
  if (src.indexOf('VCS.Figure = Figure;') < 0) throw new Error('unexpected legacy figure.js shape');
  const out = '// GENERATED by tools/build-figure-sheet.mjs from git ' + LEGACY_REF + ':js/figure.js (v0.16.0). Sheet use only.\n' +
    src.replace('VCS.Figure = Figure;', 'VCS.FigureV016 = Figure;')
      .replace("if (typeof module !== 'undefined' && module.exports) module.exports = Figure;", '');
  writeFileSync(LEGACY, out, 'utf8');
  process.stdout.write('wrote ' + LEGACY + '\n');
}

function inline(html) {
  const re = /<script src="([^"]+)"><\/script>/g;
  let n = 0;
  const outHtml = html.replace(re, function (m, src) {
    const file = resolve(dirname(SHEET), src);
    if (!file.startsWith(ROOT)) throw new Error('script outside the repo: ' + src);
    const code = readFileSync(file, 'utf8').replace(/<\/script/gi, '<\\/script');
    n++;
    return '<script>/* ' + src + ' */\n' + code + '\n</script>';
  });
  if (/<script src=|<link [^>]*href=|https?:\/\//i.test(outHtml.replace(/<script>[\s\S]*?<\/script>/g, ''))) {
    throw new Error('standalone page still references an external resource');
  }
  return { html: outHtml, n: n };
}

const args = process.argv.slice(2);
writeLegacy();
if (args.indexOf('--legacy-only') < 0) {
  const outPath = resolve(args.find((a) => !a.startsWith('--')) || join(ROOT, 'tests', 'out', 'figure-sheet-standalone.html'));
  const res = inline(readFileSync(SHEET, 'utf8').replace('<meta name="sheet-mode" content="dev">', '<meta name="sheet-mode" content="standalone">'));
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, res.html, 'utf8');
  process.stdout.write('inlined ' + res.n + ' scripts, ' + (Buffer.byteLength(res.html) / 1024).toFixed(0) + ' KB -> ' + outPath + '\n');
}
